package com.dreamsdimensions.mod.block;

import net.minecraft.util.valueproviders.IntProvider;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.DropExperienceBlock;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BooleanProperty;

/**
 * Vanilla XP/loot behavior from DropExperienceBlock.
 *
 * The old 'clicked' blockstate property is retained ONLY for save compatibility:
 * chunks generated by older DreamsDimensions versions may contain clicked=true.
 * It is deliberately not mutated by interaction and both legacy variants retain
 * the same visual model. Remove the property only with a deliberate save migration.
 */
public class DreamOreBlock extends DropExperienceBlock {
    public static final BooleanProperty CLICKED = BooleanProperty.create("clicked");

    /**
     * @param properties propriedades do bloco, definidas no registro.
     * @param xpRange    provedor de XP dropado (ex: UniformInt.of(1, 3)).
     */
    public DreamOreBlock(BlockBehaviour.Properties properties, IntProvider xpRange) {
        super(xpRange, properties);
        this.registerDefaultState(this.stateDefinition.any().setValue(CLICKED, Boolean.FALSE));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(CLICKED);
    }
}
